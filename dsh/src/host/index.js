/** Array view of a possibly missing/foreign field. */
function asArray(value) {
  return Array.isArray(value) ? value : []
}

/** Plain-object view of a possibly missing/foreign record. */
function asRecord(value) {
  return value && typeof value === 'object' && !Array.isArray(value) ? value : {}
}

/** Leading `1.2.3`-style version head, or null when the value carries none. */
function versionHead(value) {
  if (typeof value !== 'string' && typeof value !== 'number') return null
  const match = String(value).match(/^\d+(?:\.\d+){1,3}/)
  return match ? match[0] : null
}

/** True when the reported target version sorts below the installed one. */
function candidateBelowCurrent(item) {
  const tool = asRecord(item)
  const current = versionHead(tool.current)
  const latest = versionHead(tool.latest)
  if (!current || !latest) return false
  const left = current.split('.').map(Number)
  const right = latest.split('.').map(Number)
  for (let i = 0; i < Math.max(left.length, right.length); i++) {
    if ((right[i] || 0) !== (left[i] || 0)) return (right[i] || 0) < (left[i] || 0)
  }
  return false
}

/**
 * Status tone for one entry — a verbatim port of `client/view.js` `statusFor`
 * (which itself ports `dashboard/app.js`), so the Host summary and the panel
 * cannot drift.
 */
function statusTone(item, kind) {
  const tool = asRecord(item)
  if (candidateBelowCurrent(tool)) return 'anomaly'
  if (tool.outdated === true || (kind === KIND_DEP && tool.latest)) return 'update'
  if (tool.outdated == null || !tool.latest) return 'unknown'
  return 'steady'
}

/**
 * Recommendation tone for one entry — a verbatim port of
 * `client/view.js` `recommendationFor`.
 */
function recommendationTone(item, kind) {
  const tool = asRecord(item)
  const impact = asRecord(tool.impact)
  const hasImpact = tool.impact != null && typeof tool.impact === 'object'
  const dependents = asArray(impact.dependents).length
  const indirect = asArray(impact.indirect).length
  const conflicts = asArray(impact.conflicts).length
  const uncertain = asArray(impact.uncertain).length
  const scope = typeof impact.scope === 'string' ? impact.scope : ''
  const pythonScope = scope.startsWith('当前 Python')

  if (candidateBelowCurrent(tool)) return 'blocked'
  if (tool.outdated == null || !tool.latest) return 'unknown'
  if (tool.outdated === false) return 'steady'
  if (!(hasImpact && impact.checked)) return 'review'
  if (conflicts) return 'blocked'
  if (uncertain) return 'review'
  if (impact.operational_review) return 'review'
  if (kind === KIND_DEP && (dependents || indirect)) return 'review'
  if (tool.major_jump && (dependents || indirect)) return 'review'
  if (tool.major_jump) return 'review'
  if ((dependents || indirect) && !pythonScope) return 'review'
  return 'recommended'
}

/**
 * Derive the bounded v2 summary from a `check.js --json` report.
 *
 * The five v1 counters keep the dashboard scope (tool layer only); the two v2
 * counters (`conflictCount`, `uncertainCount`) additionally describe the
 * dependency layer's `impact.conflicts` / `impact.uncertain`.
 */
function summarizeReport(report, checkedAt, mode) {
  const managers = asRecord(asRecord(report).managers)
  let toolCount = 0
  let depCount = 0
  let updateCount = 0
  let recommendedCount = 0
  let reviewCount = 0
  let unknownCount = 0
  let conflictCount = 0
  let uncertainCount = 0

  for (const key of MANAGERS) {
    const manager = managers[key]
    if (!manager || typeof manager !== 'object') continue
    const tools = asArray(manager.tools)
    const deps = asArray(manager.deps)
    if (!tools.length && !deps.length) continue
    for (const tool of tools) {
      toolCount += 1
      const tone = statusTone(tool, KIND_TOOL)
      if (tone === 'update' || tone === 'review') updateCount += 1
      if (tone === 'unknown' || tone === 'anomaly') unknownCount += 1
      const recommendation = recommendationTone(tool, KIND_TOOL)
      if (recommendation === 'recommended') recommendedCount += 1
      if (recommendation === 'review' || recommendation === 'blocked') reviewCount += 1
    }
    for (const dep of deps) {
      depCount += 1
      const impact = asRecord(asRecord(dep).impact)
      if (asArray(impact.conflicts).length > 0) conflictCount += 1
      if (asArray(impact.uncertain).length > 0) uncertainCount += 1
    }
  }

  const generatedAt = typeof asRecord(report).generated_at === 'string' ? report.generated_at : null
  return {
    toolCount,
    depCount,
    updateCount,
    recommendedCount,
    reviewCount,
    unknownCount,
    conflictCount,
    uncertainCount,
    generatedAt,
    checkedAt,
    mode,
    stale: false,
  }
}

