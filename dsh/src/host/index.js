/* loopback fence                                                             */
/* -------------------------------------------------------------------------- */

/** IPv4 127/8 predicate: four decimal octets, first == 127. */
function isIPv4Loopback(value) {
  const parts = value.split('.')
  return parts.length === 4 &&
    parts[0] === '127' &&
    parts.every(part => /^\d{1,3}$/.test(part) && Number(part) <= 255)
}

/** Whether a socket remote address names the loopback range. */
function isLoopbackAddress(address) {
  if (typeof address !== 'string' || address === '') return false
  const normalized = address.toLowerCase()
  if (normalized === '::1') return true
  if (normalized.startsWith('::ffff:')) return isIPv4Loopback(normalized.slice('::ffff:'.length))
  return isIPv4Loopback(normalized)
}

/** Whether a URL hostname names a loopback authority. */
function isLoopbackHostname(hostname) {
  if (hostname === 'localhost' || hostname === '[::1]') return true
  return isIPv4Loopback(hostname)
}

/**
 * Parse a Host header as a bare loopback authority, or null when it is not one.
 * Rejects userinfo, paths, queries and non-canonical whitespace so a forged
 * authority cannot smuggle a non-loopback name past the check.
 */
function parseLoopbackAuthority(host) {
  if (typeof host !== 'string' || host === '' || host.trim() !== host) return null
  let url
  try {
    url = new URL(`http://${host}`)
  } catch {
    return null
  }
  if (url.username !== '' || url.password !== '') return null
  if (url.pathname !== '/' || url.search !== '' || url.hash !== '') return null
  if (!isLoopbackHostname(url.hostname)) return null
  return url
}

/** Whether a Cookie header carries a host browser-auth credential. */
function carriesBrowserAuthCookie(header) {
  if (typeof header !== 'string' || header === '') return false
  return header.split(';').some(segment => segment.trim().startsWith(BROWSER_AUTH_COOKIE_PREFIX))
}

/**
 * Browser signal, not an authority check: a marker-less request (bare curl) is
 * refused here, while a request that carries any of the three markers falls
 * through to the socket/Host/origin checks that carry the real authority.
 */
function browserSameOriginMarker(headers) {
  if (headers['sec-fetch-site'] === 'same-origin') return true
  if (typeof headers.origin === 'string') return true
  return carriesBrowserAuthCookie(headers.cookie)
}

/** Normalize a possibly malformed request's headers to an object. */
function requestHeaders(req) {
  const headers = req === null || typeof req !== 'object' ? undefined : req.headers
  return headers !== null && typeof headers === 'object' ? headers : {}
}

/**
 * Route fence. Every branch below must hold:
 *   - the connection is loopback (127/8, ::1, ::ffff:127/8);
 *   - Host is a loopback authority, and Origin — when present — is same-origin
 *     with it (a cross-site fetch is refused outright);
 *   - the request carries a browser same-origin marker.
 * @param req - the IncomingMessage (or a test double).
 */
function isTrustedRequest(req) {
  const headers = requestHeaders(req)
  if (!browserSameOriginMarker(headers)) return false
  const remoteAddress = req !== null && typeof req === 'object' && req.socket !== null && typeof req.socket === 'object'
    ? req.socket.remoteAddress
    : undefined
  if (!isLoopbackAddress(remoteAddress)) return false
  const hostUrl = parseLoopbackAuthority(headers.host)
  if (hostUrl === null) return false
  if (headers['sec-fetch-site'] === 'cross-site') return false
  const origin = headers.origin
  if (origin !== undefined) {
    if (typeof origin !== 'string') return false
    let originUrl
    try {
      originUrl = new URL(origin)
    } catch {
      return false
    }
    if (originUrl.host !== hostUrl.host) return false
  }
  return true
}

