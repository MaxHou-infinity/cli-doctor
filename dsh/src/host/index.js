/**
 * cli-doctor — DSH Host half.
 *
 * A Cordis function plugin with zero third-party imports: every module it
 * touches comes from the `node:` builtin namespace. It owns one prefix route,
 * `/api/cli-doctor`, which exposes the read-only diagnosis surface described by
 * `CONTRACT.md` §2 (v1) plus the v2 additions in §v2.1/§v2.2:
 *
 *   GET | HEAD /api/cli-doctor/health              liveness + capabilities + lastCheck
 *   GET | HEAD /api/cli-doctor/snapshot[?full=1]   cached snapshot (summary; report with full=1)
 *   GET | HEAD /api/cli-doctor/status              running / lastCheck / cache view
 *   GET | HEAD /api/cli-doctor/history[?limit=N]   newest-first summary history
 *   POST      /api/cli-doctor/check[?mode=fast|full][&force=0]
 *   POST      /api/cli-doctor/check/cancel         cancel the in-flight run
 *
 * The diagnosis itself is delegated to the vendored, read-only copy of the
 * repository's `bin/check.js` (generated by scripts/sync-shared.mjs). The
 * plugin never upgrades anything; it only reports.
 *
 * Concurrency model (v2): there is no 409 any more. One run is in flight at a
 * time; every concurrent request attaches to it as a waiter and receives the
 * same result (`cache:'attached'`, `shared:true`). A request whose response
 * socket closes simply stops waiting — the run keeps going and caches its
 * result for later (`GET /snapshot`).
 *
 * Termination: cancel / timeout / fiber disposal terminate the subprocess by
 * process group on POSIX (spawned detached) or `taskkill /T /F` on Windows,
 * escalating SIGTERM → SIGKILL after a grace period. `busy` only clears once
 * the child really closed.
 *
 * State: an in-memory snapshot plus a bounded summary history, persisted to
 * `<dataDir>/state.json` with an atomic temp-file + fsync + rename write. Load
 * and corrupt-file handling never throw; write failures only log. Tests inject
 * `dataDir` or `persist:false` and therefore never touch the real `~/.dsh`.
 *
 * The route is fenced three ways (see isTrustedRequest): a loopback socket
 * address, a loopback Host authority, and a browser same-origin marker. The
 * marker branch that accepts the `dsh-auth-*` cookie exists because the DSH
 * Desktop shell serves the Web GUI from `dsh-app://app/` and forwards its
 * requests after deleting `Origin` and `sec-fetch-site` — the signed cookie it
 * attaches in their place is the only signal such a request carries.
 *
 * Testing seams (all optional, defaults are the production values): `spawn`,
 * `execPath`, `checkPath`, `checkTimeoutMs` / `timeoutMs`, `maxOutputBytes`,
 * `killGraceMs`, `dataDir`, `persist`, `autoCheck`, `staleAfterHours`,
 * `keepHistory` and `logger` may be passed through the plugin config object so
 * tests never run a real diagnosis and never write the user's harness home.
 *
 * @module dsh-cli-doctor/host
 */

