/**
 * Cordis plugin entry: register the `/api/cli-doctor` prefix route and bind it
 * (plus any in-flight diagnosis) to the fiber lifecycle.
 * @param ctx - the plugin context, providing `webServer` and `effect`.
 * @param config - optional overrides; defaults are the production values.
 */
export function apply(ctx, config) {
  const options = resolveOptions(config)
  const state = {
    options,
    snapshot: null,
    history: [],
    inflight: null,
    persistSequence: 0,
  }
  loadState(state)
  const handler = (req, res) => { handleRequest(req, res, state) }

  ctx.effect(() => {
    const disposeRoute = ctx.webServer.register({ kind: 'prefix', path: API_PREFIX, handler })
    return () => {
      try {
        if (typeof disposeRoute === 'function') disposeRoute()
      } catch (error) {
        log(options, `route disposal failed: ${messageOf(error)}`)
      }
      killCurrent(state)
    }
  }, 'cli-doctor: routes')
}
