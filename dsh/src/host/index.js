/** Package version for the health payload; 'unknown' if package.json is unreadable. */
function packageVersion(pkgRoot) {
  try {
    const pkg = JSON.parse(readFileSync(path.join(pkgRoot, 'package.json'), 'utf8'))
    return pkg !== null && typeof pkg === 'object' && typeof pkg.version === 'string' && pkg.version !== ''
      ? pkg.version
      : 'unknown'
  } catch {
    return 'unknown'
  }
}

/** Positive finite number, or the fallback. */
function positiveNumber(value, fallback) {
  return Number.isFinite(value) && value > 0 ? value : fallback
}

/** Non-empty harness home from the environment, or the default ~/.dsh. */
function resolveDshHome() {
  const configured = process.env.DSH_HOME
  if (typeof configured === 'string' && configured.trim() !== '') return configured
  return path.join(homedir(), '.dsh')
}

/** Default on-disk state directory, following the harness storage convention. */
function defaultDataDir() {
  return path.join(resolveDshHome(), 'storages', 'cli-doctor')
}

/** Whether the environment seam forces synchronous auto-check to on/off. */
function autoCheckOverride() {
  const raw = process.env.CLI_DOCTOR_AUTO_CHECK
  if (raw === '0') return false
  if (raw === '1') return true
  return undefined
}

/**
 * Resolve the effective plugin options. Every value has a production default;
 * the config object only exists so tests can replace the subprocess/storage
 * seams.
 */
function resolveOptions(config) {
  const cfg = config !== null && typeof config === 'object' ? config : {}
  const checkPath = typeof cfg.checkPath === 'string' && cfg.checkPath !== ''
    ? cfg.checkPath
    : (typeof process.env.CLI_DOCTOR_CHECK_PATH === 'string' && process.env.CLI_DOCTOR_CHECK_PATH !== ''
        ? process.env.CLI_DOCTOR_CHECK_PATH
        : path.join(PKG_ROOT, 'bin', 'check.js'))
  const autoCheck = typeof cfg.autoCheck === 'boolean' ? cfg.autoCheck : true
  const staleAfterHours = positiveNumber(cfg.staleAfterHours, DEFAULT_STALE_AFTER_HOURS)
  return {
    pkgRoot: PKG_ROOT,
    version: packageVersion(PKG_ROOT),
    checkPath,
    execPath: typeof cfg.execPath === 'string' && cfg.execPath !== '' ? cfg.execPath : process.execPath,
    spawn: typeof cfg.spawn === 'function' ? cfg.spawn : spawn,
    checkTimeoutMs: positiveNumber(cfg.checkTimeoutMs, positiveNumber(cfg.timeoutMs, DEFAULT_CHECK_TIMEOUT_MS)),
    maxOutputBytes: positiveNumber(cfg.maxOutputBytes, MAX_OUTPUT_BYTES),
    killGraceMs: positiveNumber(cfg.killGraceMs, DEFAULT_KILL_GRACE_MS),
    staleAfterHours,
    ttlMs: staleAfterHours * 60 * 60 * 1000,
    keepHistory: Number.isFinite(cfg.keepHistory) && cfg.keepHistory >= 0
      ? Math.min(Math.floor(cfg.keepHistory), MAX_HISTORY_LIMIT)
      : DEFAULT_KEEP_HISTORY,
    dataDir: typeof cfg.dataDir === 'string' && cfg.dataDir !== '' ? path.resolve(cfg.dataDir) : defaultDataDir(),
    persist: cfg.persist !== false,
    autoCheck: autoCheckOverride() ?? autoCheck,
    logger: typeof cfg.logger === 'function' ? cfg.logger : defaultLogger,
  }
}

/** Log a failure to the host stderr (or the injected logger) without throwing. */
function log(options, message) {
  try {
    options.logger(message)
  } catch {
    /* a broken logger must never break a request */
  }
}

