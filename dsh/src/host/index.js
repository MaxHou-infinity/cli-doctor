/**
 * Parsed request target, parsed exactly like the host web server's own route
 * matcher (`new URL(req.url, 'http://x')`), so a target the router matched can
 * never fall through as not-found here: origin-form and absolute-form targets,
 * queries and fragments all resolve to the same path.
 */
function requestUrl(req) {
  const target = req !== null && typeof req === 'object' ? req.url : undefined
  if (typeof target !== 'string' || target === '') return null
  try {
    return new URL(target, 'http://x')
  } catch {
    return null
  }
}

function requestMethod(req) {
  const method = req !== null && typeof req === 'object' ? req.method : undefined
  return typeof method === 'string' ? method.toUpperCase() : ''
}

/** Method gate shared by every known path; writes the 405 body itself. */
function allowMethods(req, res, allowed) {
  const method = requestMethod(req)
  if (allowed.includes(method)) return method
  writeJson(res, 405, { ok: false, error: 'method' })
  return null
}

/** The fence gate shared by every known path; writes the 403 body itself. */
function allowTrusted(req, res) {
  if (isTrustedRequest(req)) return true
  writeJson(res, 403, { ok: false, error: 'forbidden' })
  return false
}

/** Whether a HEAD response must omit the body. */
function isHead(req) {
  return requestMethod(req) === 'HEAD'
}

/** Shared query helpers. */
function isForceRequested(url) {
  const force = url.searchParams.get('force')
  return force !== '0'
}

function requestedMode(url) {
  return url.searchParams.get('mode') === 'fast' ? 'fast' : 'full'
}

function historyLimit(url, fallback) {
  const raw = url.searchParams.get('limit')
  if (raw === null) return fallback
  const parsed = Number(raw)
  if (!Number.isFinite(parsed) || parsed < 1) return fallback
  return Math.min(Math.floor(parsed), MAX_HISTORY_LIMIT)
}

/** The one registered route handler. Never lets a failure escape as a 400. */
function handleRequest(req, res, state) {
  let pending
  try {
    pending = dispatch(req, res, state)
  } catch (error) {
    failRequest(res, state, error)
    return
  }
  if (pending !== null && pending !== undefined && typeof pending.then === 'function') {
    pending.catch(error => { failRequest(res, state, error) })
  }
}

function dispatch(req, res, state) {
  const url = requestUrl(req)
  const pathname = url === null ? '' : url.pathname
  const method = requestMethod(req)

  if (pathname === HEALTH_PATH) {
    if (allowMethods(req, res, ['GET', 'HEAD']) === null) return
    if (!allowTrusted(req, res)) return
    writeJson(res, 200, {
      ok: true,
      version: state.options.version,
      busy: state.inflight !== null,
      capabilities: { snapshot: true, history: true, cancel: true },
      lastCheck: lastCheckOf(state),
    }, isHead(req))
    return
  }

  if (pathname === SNAPSHOT_PATH) {
    if (allowMethods(req, res, ['GET', 'HEAD']) === null) return
    if (!allowTrusted(req, res)) return
    writeJson(res, 200, {
      ok: true,
      snapshot: snapshotOf(state, url.searchParams.get('full') === '1'),
      busy: state.inflight !== null,
      cache: { ttlMs: state.options.ttlMs, autoCheck: state.options.autoCheck },
    }, isHead(req))
    return
  }

  if (pathname === STATUS_PATH) {
    if (allowMethods(req, res, ['GET', 'HEAD']) === null) return
    if (!allowTrusted(req, res)) return
    const run = state.inflight
    writeJson(res, 200, {
      ok: true,
      busy: run !== null,
      running: run === null
        ? null
        : {
            startedAt: run.startedAt,
            elapsedMs: Date.now() - run.startedAtMs,
            mode: run.mode,
            waiters: run.waiters.size,
          },
      lastCheck: lastCheckOf(state),
      cache: { ttlMs: state.options.ttlMs },
    }, isHead(req))
    return
  }

  if (pathname === HISTORY_PATH) {
    if (allowMethods(req, res, ['GET', 'HEAD']) === null) return
    if (!allowTrusted(req, res)) return
    const limit = historyLimit(url, DEFAULT_KEEP_HISTORY)
    writeJson(res, 200, {
      ok: true,
      entries: state.history.slice(0, limit).map(entry => ({
        checkedAt: entry.checkedAt,
        mode: entry.mode,
        elapsedMs: entry.elapsedMs,
        summary: entry.summary,
      })),
    }, isHead(req))
    return
  }

  if (pathname === CHECK_PATH) {
    if (allowMethods(req, res, ['POST']) === null) return
    if (!allowTrusted(req, res)) return
    handleCheck(req, res, state, url)
    return
  }

  if (pathname === CANCEL_PATH) {
    if (allowMethods(req, res, ['POST']) === null) return
    if (!allowTrusted(req, res)) return
    writeJson(res, 200, { ok: true, cancelled: cancelRun(state) })
    return
  }

  writeJson(res, 404, { ok: false, error: 'not-found' })
}

/**
 * POST /check: attach to the in-flight run when there is one, answer from the
 * cache when `force=0` and the snapshot is fresh, otherwise start one shared
 * run. There is no 409: single-flight is enforced by the shared run itself.
 */
function handleCheck(req, res, state, url) {
  const run = state.inflight
  if (run !== null && run !== undefined) {
    attachWaiter(run, state, res, 'attached')
    return
  }

  const mode = requestedMode(url)
  if (!isForceRequested(url) && state.snapshot !== null && state.snapshot !== undefined) {
    const ageMs = ageMsOf(state.snapshot.checkedAt)
    if (!isStale(state, ageMs)) {
      const snapshot = state.snapshot
      writeJson(res, 200, {
        ok: true,
        report: snapshot.report,
        checkedAt: snapshot.checkedAt,
        mode: snapshot.mode,
        elapsedMs: snapshot.elapsedMs,
        cache: 'hit',
        shared: false,
      })
      return
    }
  }

  const nextRun = createRun(mode)
  nextRun.killGraceMs = state.options.killGraceMs
  state.inflight = nextRun
  attachWaiter(nextRun, state, res, 'fresh')
  startDiagnosis(nextRun, state, mode)
}

/** Last-resort failure path for unexpected errors thrown outside a run. */
function failRequest(res, state, error) {
  const reason = error instanceof CheckFailure
    ? error.code
    : (error instanceof Error && error.message !== '' ? error.message : 'internal')
  log(state.options, `request failed (${reason}): ${messageOf(error)}`)
  safeWriteJson(res, 500, { ok: false, error: reason })
}

