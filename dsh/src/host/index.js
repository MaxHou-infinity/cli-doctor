/** Merge the diagnosis environment hygiene without overriding explicit values. */
function diagnosisEnv(baseEnv) {
  const source = baseEnv !== null && typeof baseEnv === 'object' ? baseEnv : {}
  const env = { ...source }
  for (const [key, value] of Object.entries(CHILD_ENV_HYGIENE)) {
    if (env[key] === undefined) env[key] = value
  }
  return env
}

/** Argument vector for one diagnosis, per CONTRACT v2 §v2.2. */
function diagnosisArgs(mode) {
  if (mode === 'fast') return ['--json', '--fast', '--no-update']
  return ['--json', '--no-update']
}

/** Timers in the plugin are unref'd so tests and shutdowns cannot hang on them. */
function unrefTimer(timer) {
  if (timer !== null && typeof timer === 'object' && typeof timer.unref === 'function') timer.unref()
  return timer
}

function clearTimer(timer) {
  if (timer === null || timer === undefined) return null
  clearTimeout(timer)
  return null
}

/** Create the in-memory run record that every waiter attaches to. */
function createRun(mode) {
  const startedAtMs = Date.now()
  const run = {
    startedAtMs,
    startedAt: new Date(startedAtMs).toISOString(),
    mode,
    waiters: new Set(),
    child: null,
    promise: null,
    resolve: null,
    settled: false,
    cancelled: false,
    terminating: false,
    timeoutTimer: null,
    killTimer: null,
    elapsedMs: null,
  }
  run.promise = new Promise((resolve) => { run.resolve = resolve })
  return run
}

/**
 * Start one diagnosis for an already-registered run: spawn, wire stdout/stderr,
 * deadline and failure mapping. A synchronous spawn failure settles the run
 * before returning.
 */
function startDiagnosis(run, state, mode) {
  const options = state.options
  let child
  try {
    child = options.spawn(options.execPath, [options.checkPath, ...diagnosisArgs(mode)], {
      cwd: options.pkgRoot,
      env: diagnosisEnv(process.env),
      ...(process.platform === 'win32' ? {} : { detached: true }),
    })
  } catch (error) {
    failRun(run, state, 'spawn-error', messageOf(error))
    return
  }
  if (child === null || typeof child !== 'object' || typeof child.on !== 'function') {
    failRun(run, state, 'spawn-error', 'spawn returned no child process')
    return
  }
  run.child = child

  const stdoutChunks = []
  const stderrChunks = []
  let stdoutBytes = 0
  let stderrBytes = 0

  function onStdout(chunk) {
    if (run.settled) return
    const buffer = toBuffer(chunk)
    stdoutBytes += buffer.length
    if (stdoutBytes > options.maxOutputBytes) {
      terminateRun(run)
      failRun(run, state, 'output-too-large', `stdout exceeded ${options.maxOutputBytes} bytes`)
      return
    }
    stdoutChunks.push(buffer)
  }

  function onStderr(chunk) {
    if (run.settled) return
    const buffer = toBuffer(chunk)
    stderrChunks.push(buffer)
    stderrBytes += buffer.length
    while (stderrChunks.length > 1 && stderrBytes - stderrChunks[0].length > MAX_STDERR_BYTES) {
      stderrBytes -= stderrChunks.shift().length
    }
  }

  function onError(error) {
    failRun(run, state, 'spawn-error', messageOf(error))
    finishRun(run, state)
  }

  function onClose(code, signal) {
    if (!run.settled) {
      const stderr = Buffer.concat(stderrChunks).toString('utf8').trim()
      if (code !== 0) {
        const reason = code === null || code === undefined
          ? `signal-${signal === null || signal === undefined ? 'unknown' : signal}`
          : `exit-${code}`
        failRun(run, state, reason, stderr === '' ? 'check.js failed without stderr' : `check.js stderr: ${stderr}`)
      } else {
        let report
        try {
          report = JSON.parse(Buffer.concat(stdoutChunks).toString('utf8'))
        } catch (error) {
          failRun(run, state, 'invalid-json', `check.js stdout is not valid JSON (${messageOf(error)})`)
        }
        if (report !== undefined) succeedRun(run, state, report)
      }
    }
    finishRun(run, state)
  }

  if (child.stdout !== null && child.stdout !== undefined && typeof child.stdout.on === 'function') {
    child.stdout.on('data', onStdout)
  }
  if (child.stderr !== null && child.stderr !== undefined && typeof child.stderr.on === 'function') {
    child.stderr.on('data', onStderr)
  }
  child.on('error', onError)
  child.on('close', onClose)

  run.timeoutTimer = unrefTimer(setTimeout(() => {
    run.timeoutTimer = null
    if (run.settled) return
    terminateRun(run)
    failRun(run, state, 'timeout', `check.js did not finish within ${options.checkTimeoutMs} ms`)
  }, options.checkTimeoutMs))
}

/** Settle a run with a failure result, log it, and write every current waiter. */
function failRun(run, state, code, detail) {
  log(state.options, `diagnosis failed (${code}): ${detail === undefined ? code : detail}`)
  settleRun(run, state, { ok: false, code, detail })
}

/** Settle a run with a successful report: snapshot, history, persistence. */
function succeedRun(run, state, report) {
  const options = state.options
  run.elapsedMs = Date.now() - run.startedAtMs
  const checkedAt = new Date().toISOString()
  const summary = summarizeReport(report, checkedAt, run.mode)
  state.snapshot = {
    report,
    checkedAt,
    mode: run.mode,
    elapsedMs: run.elapsedMs,
    summary,
  }
  if (options.keepHistory > 0) {
    state.history = [
      { checkedAt, mode: run.mode, elapsedMs: run.elapsedMs, summary },
      ...state.history,
    ].slice(0, options.keepHistory)
  }
  settleRun(run, state, { ok: true, report })
  persistState(state)
}

/**
 * Terminate a run's subprocess. POSIX kills the detached process group (so
 * check.js's own brew/npm/pip children die too); Windows uses `taskkill /T /F`.
 * SIGTERM is followed by SIGKILL after `killGraceMs`.
 */
function terminateRun(run) {
  if (run.terminating) return
  run.terminating = true
  const child = run.child
  try {
    if (child !== null && typeof child === 'object') {
      const pid = child.pid
      if (process.platform === 'win32') {
        if (Number.isFinite(pid)) {
          try {
            spawn('taskkill', ['/T', '/F', '/PID', String(pid)], { stdio: 'ignore' }).on?.('error', () => {})
          } catch { /* taskkill is best effort */ }
        } else if (typeof child.kill === 'function') {
          child.kill('SIGTERM')
        }
      } else if (Number.isFinite(pid)) {
        try {
          process.kill(-pid, 'SIGTERM')
        } catch {
          if (typeof child.kill === 'function') child.kill('SIGTERM')
        }
      } else if (typeof child.kill === 'function') {
        child.kill('SIGTERM')
      }
    }
  } catch { /* the child is already gone */ }

  if (process.platform !== 'win32') {
    run.killTimer = unrefTimer(setTimeout(() => {
      run.killTimer = null
      const current = run.child
      if (current === null || typeof current !== 'object') return
      const pid = current.pid
      try {
        if (Number.isFinite(pid)) process.kill(-pid, 'SIGKILL')
        else if (typeof current.kill === 'function') current.kill('SIGKILL')
      } catch {
        try { if (typeof current.kill === 'function') current.kill('SIGKILL') } catch { /* gone */ }
      }
    }, run.killGraceMs))
  }
}

/** Per-waiter cache token: the initiating request is `fresh`, attaches are `attached`. */
function waiterBody(run, state, waiter) {
  if (run.settled && run.result && run.result.ok) {
    return {
      ok: true,
      report: run.result.report,
      checkedAt: state.snapshot === null ? null : state.snapshot.checkedAt,
      mode: run.mode,
      elapsedMs: run.elapsedMs,
      cache: waiter.cache,
      shared: waiter.cache === 'attached',
    }
  }
  const code = run.result === null || run.result === undefined ? 'internal' : run.result.code
  const body = { ok: false, error: code }
  const detail = failureDetail(run)
  if (detail !== undefined) body.detail = detail
  if (Number.isFinite(run.elapsedMs)) body.elapsedMs = run.elapsedMs
  return body
}

/** Trim a failure's stderr tail to the contract's 2 KiB bound, or undefined. */
function failureDetail(run) {
  const raw = run === null || run === undefined || run.result === null || run.result === undefined
    ? undefined
    : run.result.detail
  if (typeof raw !== 'string') return undefined
  const detail = raw.trim()
  if (detail === '') return undefined
  return detail.length > MAX_ERROR_DETAIL_BYTES ? detail.slice(-MAX_ERROR_DETAIL_BYTES) : detail
}

/** Write one waiter's response (never throws). */
function writeWaiter(run, state, waiter) {
  const body = waiterBody(run, state, waiter)
  if (body.ok === true) safeWriteJson(waiter.res, 200, body)
  else safeWriteJson(waiter.res, 500, body)
}

/**
 * Settle a run exactly once: cache the success, remember the failure result and
 * answer every waiter. `busy` is not cleared here — `finishRun` does that when
 * the child process really closed.
 */
function settleRun(run, state, result) {
  if (run.settled) return
  run.settled = true
  run.result = result
  if (run.elapsedMs === null) run.elapsedMs = Date.now() - run.startedAtMs
  run.timeoutTimer = clearTimer(run.timeoutTimer)
  const waiters = [...run.waiters]
  run.waiters.clear()
  for (const waiter of waiters) writeWaiter(run, state, waiter)
  run.resolve(result)
}

/** Clear the run from the inflight slot and drop any pending kill escalation. */
function finishRun(run, state) {
  run.timeoutTimer = clearTimer(run.timeoutTimer)
  run.killTimer = clearTimer(run.killTimer)
  if (state.inflight === run) state.inflight = null
}

/** Attach a response waiter to the run, writing at once when already settled. */
function attachWaiter(run, state, res, cache) {
  const waiter = { res, cache, closed: false }
  if (typeof res === 'object' && res !== null && typeof res.once === 'function') {
    try {
      res.once('close', () => {
        waiter.closed = true
        run.waiters.delete(waiter)
      })
    } catch { /* a broken response must not break the run */ }
  }
  if (run.settled) {
    writeWaiter(run, state, waiter)
    return waiter
  }
  run.waiters.add(waiter)
  return waiter
}

/**
 * Cancel the current run, if any. All waiters receive `500 cancelled`; `busy`
 * remains true until the child actually closes. Returns whether a run was
 * cancelled.
 */
function cancelRun(state) {
  const run = state.inflight
  if (run === null || run === undefined) return false
  if (!run.settled) {
    run.cancelled = true
    settleRun(run, state, { ok: false, code: 'cancelled' })
    terminateRun(run)
  } else {
    run.cancelled = true
    terminateRun(run)
  }
  return true
}

/** Stop an in-flight diagnosis when the plugin fiber is disposed. */
function killCurrent(state) {
  const run = state.inflight
  if (run === null || run === undefined) return
  if (!run.settled) {
    run.cancelled = true
    settleRun(run, state, { ok: false, code: 'cancelled' })
  }
  terminateRun(run)
}

