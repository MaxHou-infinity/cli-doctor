/** Age of an ISO timestamp in ms, or null when it cannot be parsed. */
function ageMsOf(checkedAt) {
  const parsed = Date.parse(checkedAt)
  if (!Number.isFinite(parsed)) return null
  return Math.max(0, Date.now() - parsed)
}

/** Whether a snapshot age (or an unparseable timestamp) counts as stale. */
function isStale(state, ageMs) {
  return ageMs === null || ageMs >= state.options.ttlMs
}

/** The `lastCheck` object shared by /health and /status. */
function lastCheckOf(state) {
  const snapshot = state.snapshot
  if (snapshot === null || snapshot === undefined) return null
  return {
    checkedAt: snapshot.checkedAt,
    mode: snapshot.mode,
    ageMs: ageMsOf(snapshot.checkedAt),
  }
}

/** The /snapshot payload (without the envelope). */
function snapshotOf(state, includeReport) {
  const snapshot = state.snapshot
  if (snapshot === null || snapshot === undefined) return null
  const ageMs = ageMsOf(snapshot.checkedAt)
  const stale = isStale(state, ageMs)
  const payload = {
    checkedAt: snapshot.checkedAt,
    mode: snapshot.mode,
    elapsedMs: snapshot.elapsedMs,
    ageMs,
    stale,
    summary: { ...snapshot.summary, stale },
  }
  if (includeReport) payload.report = snapshot.report
  return payload
}

