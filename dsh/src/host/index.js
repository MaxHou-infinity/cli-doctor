/** Parse-time guard for a restored snapshot record. */
function sanitizeSnapshot(value) {
  const record = asRecord(value)
  if (typeof record.checkedAt !== 'string' || record.checkedAt === '') return null
  if (record.mode !== 'fast' && record.mode !== 'full') return null
  if (!Number.isFinite(record.elapsedMs) || record.elapsedMs < 0) return null
  if (!record.report || typeof record.report !== 'object' || Array.isArray(record.report)) return null
  return {
    report: record.report,
    checkedAt: record.checkedAt,
    mode: record.mode,
    elapsedMs: record.elapsedMs,
  }
}

/** Parse-time guard for one restored history entry. */
function sanitizeHistoryEntry(value) {
  const record = asRecord(value)
  if (typeof record.checkedAt !== 'string' || record.checkedAt === '') return null
  if (record.mode !== 'fast' && record.mode !== 'full') return null
  if (!Number.isFinite(record.elapsedMs) || record.elapsedMs < 0) return null
  if (!record.summary || typeof record.summary !== 'object' || Array.isArray(record.summary)) return null
  return {
    checkedAt: record.checkedAt,
    mode: record.mode,
    elapsedMs: record.elapsedMs,
    summary: record.summary,
  }
}

/**
 * Load `<dataDir>/state.json` into memory. Corrupt, absent or unsupported files
 * are ignored and the plugin starts empty; this function never throws and stays
 * well under the 50 ms budget for the real 150 KB report.
 */
function loadState(state) {
  const options = state.options
  if (!options.persist) return
  let raw
  try {
    raw = readFileSync(path.join(options.dataDir, STATE_FILE_NAME), 'utf8')
  } catch {
    return
  }
  if (typeof raw !== 'string' || raw.length > MAX_STATE_BYTES) return
  let parsed
  try {
    parsed = JSON.parse(raw)
  } catch {
    return
  }
  if (parsed === null || typeof parsed !== 'object' || parsed.schemaVersion !== STATE_SCHEMA_VERSION) return
  const snapshot = sanitizeSnapshot(parsed.snapshot)
  if (snapshot !== null) {
    state.snapshot = {
      ...snapshot,
      summary: summarizeReport(snapshot.report, snapshot.checkedAt, snapshot.mode),
    }
  }
  const history = Array.isArray(parsed.history) ? parsed.history : []
  state.history = history
    .map(sanitizeHistoryEntry)
    .filter(entry => entry !== null)
    .slice(0, options.keepHistory)
}

/**
 * Persist the in-memory state atomically: same-directory temp file, fsync, then
 * rename. Directory 0700 / file 0600. Any failure is logged only — persistence
 * must never affect a diagnosis response.
 */
function persistState(state) {
  const options = state.options
  if (!options.persist) return
  let tempPath = null
  try {
    mkdirSync(options.dataDir, { recursive: true, mode: 0o700 })
    const statePath = path.join(options.dataDir, STATE_FILE_NAME)
    const snapshot = state.snapshot === null
      ? null
      : {
          report: state.snapshot.report,
          checkedAt: state.snapshot.checkedAt,
          mode: state.snapshot.mode,
          elapsedMs: state.snapshot.elapsedMs,
        }
    const payload = JSON.stringify({
      schemaVersion: STATE_SCHEMA_VERSION,
      snapshot,
      history: state.history,
    })
    tempPath = path.join(
      options.dataDir,
      `.${STATE_FILE_NAME}.${process.pid}.${Date.now()}.${state.persistSequence += 1}.tmp`,
    )
    const descriptor = openSync(tempPath, 'wx', 0o600)
    try {
      writeFileSync(descriptor, payload)
      fsyncSync(descriptor)
    } finally {
      closeSync(descriptor)
    }
    renameSync(tempPath, statePath)
    tempPath = null
  } catch (error) {
    log(options, `state persistence failed: ${messageOf(error)}`)
    if (tempPath !== null) {
      try { unlinkSync(tempPath) } catch { /* already gone */ }
    }
  }
}

