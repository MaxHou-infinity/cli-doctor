/** Structured diagnosis failure: a stable machine-readable code plus detail. */
class CheckFailure extends Error {
  constructor(code, detail) {
    super(detail === undefined ? code : `${code}: ${detail}`)
    this.name = 'CheckFailure'
    this.code = code
    this.detail = detail
  }
}

function messageOf(error) {
  if (error instanceof Error) return error.message
  return String(error)
}

function toBuffer(chunk) {
  return Buffer.isBuffer(chunk) ? chunk : Buffer.from(String(chunk))
}

/** Default logger: failures go to the host process stderr, never to the client. */
function defaultLogger(message) {
  try {
    process.stderr.write(`[cli-doctor] ${message}\n`)
  } catch {
    /* stderr may be closed while the host shuts down */
  }
}

