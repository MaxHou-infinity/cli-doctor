/**
 * Write one JSON response with the contract headers. HEAD responses carry the
 * status and headers but no body, per HTTP.
 * @param res - the ServerResponse (or a test double with writeHead/end).
 * @param status - HTTP status code.
 * @param body - JSON-serializable payload.
 * @param omitBody - true for HEAD.
 */
function writeJson(res, status, body, omitBody = false) {
  res.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'cache-control': 'no-store',
  })
  res.end(omitBody ? undefined : JSON.stringify(body))
}

/**
 * Write a failure response without ever throwing: a handler that throws is
 * turned into a 400 by the host web server, which would hide the real status.
 */
function safeWriteJson(res, status, body) {
  try {
    if (res.headersSent === true || res.writableEnded === true) {
      try { res.end() } catch { /* the socket is already gone */ }
      return
    }
    writeJson(res, status, body)
  } catch {
    /* nothing left to do: the response stream is unusable */
  }
}

